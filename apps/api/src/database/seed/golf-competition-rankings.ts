/**
 * Roll of honour for the nine golf majors.
 *
 * The competition pages for the majors rendered almost nothing: the Masters
 * carried no winners, no records and no history, which on a tournament first
 * played in 1934 is the most conspicuous gap in the golf section. This file is
 * the champions, one table per major.
 *
 * ## One table per major, not per tour
 *
 * Golf reports its majors individually and a career is counted in them, so each
 * gets its own table keyed by competition. `kind` is the conflict target on
 * `entity_ranking`, and every table here uses `champions_golf`: unlike tennis,
 * which awards five titles at each event and therefore needs five kinds, golf
 * awards one.
 *
 * ## Complete histories, not the modern era
 *
 * Every table runs from the tournament's first playing. Tennis's equivalent
 * starts at 1968 because the pre-Open majors excluded professionals and the
 * trophy meant a different thing; golf has no such break. The Open Championship
 * has been open to professionals since 1860, and Bobby Jones's 1930 Grand Slam
 * is not a lesser achievement for having been won as an amateur. Where a
 * champion was an amateur the row says so in its detail rather than being
 * omitted or silently merged with the professionals.
 *
 * The PGA Championship's table spans both of its formats. It was match play
 * from 1916 to 1957 and stroke play since 1958, and Wikipedia splits it across
 * two tables for that reason; they are merged here because it is one
 * championship with one continuous roll of champions, and a page that showed
 * only the stroke-play era would lose every one of Walter Hagen's five titles.
 *
 * ## Gaps are real
 *
 * Missing years are years the tournament was not played, and are left absent
 * rather than interpolated. The Open Championship was not held during either
 * world war, the Masters was suspended from 1943 to 1945, and the 2020 Open was
 * cancelled. A missing year here never means the winner is unknown.
 *
 * ## Provenance
 *
 * Extracted from each tournament's Wikipedia article at the `asOf` date by a
 * one-off script, not recalled: a roll of honour written from memory would be
 * wrong in ways nobody could spot. The source URL is stored per table and
 * rendered as the provenance note. Champion names are stored as written; the
 * seeder resolves them against the person table, and an unmatched name renders
 * as plain text rather than a wrong link.
 *
 * `value` is the year and `detail` carries the winning score, the score to par
 * and the margin, which is how golf reports a result. A match-play era PGA
 * Championship has a margin like "1 up" and no score to par, because the format
 * had none.
 */
