/**
 * The Formula 1 taxonomy: the categories, and every concept the library intends
 * to cover.
 *
 * Everything in this file is a draft placeholder. Nothing here reaches the site.
 * The written explainers live in the `formula1-*.ts` content files and override
 * these by slug, which is why the slugs here have to be right first time: a typo
 * produces a second concept rather than a written version of the first.
 *
 * ## On categories
 *
 * The brief names thirty-one groupings. Thirty-one headings on a landing page is
 * a directory rather than a structure, so the categories are ordered and the
 * landing page leads with the first ten; the rest are real categories with real
 * URLs, reachable from a breadcrumb and from search. Tennis and basketball
 * reached the same arrangement for the same reason.
 *
 * Several of the brief's groupings collapse here, because they name the same
 * concepts twice rather than naming two things:
 *
 * - **Race Weekend** and **Qualifying** overlap on the flying lap, the out lap
 *   and track evolution. Qualifying keeps them; the weekend category links to
 *   them through `alsoIn`.
 * - **Pit Stops** and **Race Strategy** both claim the pit window and the
 *   undercut. The mechanical concepts (pit lane, crew roles, double stacking)
 *   sit in Pit Stops; the decisions (undercut, overcut, offset) sit in Strategy.
 *   `pit-window` is one row in both.
 * - **Overtaking** and **Track Limits & Racing Rules** both claim leaving the
 *   track, racing room and moving under braking. Those are rules, so they live
 *   in Rules & Track Limits and appear in Overtaking through `alsoIn`.
 * - **F1 Car Basics** and **Aerodynamics** both claim the diffuser, the wings
 *   and the floor. The parts are components; the physics is aerodynamics. The
 *   diffuser is one row, typed `car_component`, in both.
 * - **Braking & Cornering** and **Driver Skills** both claim trail braking and
 *   the racing line. They are techniques, filed under Driving, with Braking &
 *   Cornering folded in rather than split from it.
 * - **Lap Times** and **Telemetry & Data** both claim sector times, delta time
 *   and fuel correction. One category, Telemetry & Lap Time.
 * - **Cost Cap & Business**, **Driver Market** and **Feeder Series** are three
 *   small categories about the sport's economics and its pathway. Two here:
 *   Business, and Getting to F1.
 * - **Advanced Performance Analysis** stays its own category. It is the one
 *   place in the library where the content is derived rather than reported, and
 *   keeping it together is what lets every entry in it carry the same warning.
 *
 * That is twenty-two categories covering all thirty-one of the brief's, with no
 * concept dropped and none duplicated.
 *
 * ## On versioning
 *
 * The brief asks three times for content to be versioned by season or
 * regulation era, and this is the sport where that matters most: there is one
 * Formula 1, but a 2013 car, a 2021 car and a 2026 car are three different
 * machines run under three different rulebooks. Every entry written against a
 * regulation carries `ruleSensitive: true` and a `sourceRevision`, and the
 * helper's `era` field puts the same statement on the page where the reader
 * can see it. The set to re-audit after a rule change is then a query rather
 * than a reading of four hundred articles.
 */

