/**
 * Builds a taxonomy placeholder.
 *
 * A row with no sections: the concept is named and categorised, but unwritten,
 * so it stays a draft and never reaches the site. This is what makes duplicate
 * control work before the writing happens, since a proposed explainer can be
 * checked against every concept the library intends to cover rather than only
 * against the ones already finished.
 */
function topic(
  slug: string,
  title: string,
  type: ExplainerSeed['type'],
  difficulty: ExplainerSeed['difficulty'],
  category: string,
  order: number,
  alsoIn?: string[],
): ExplainerSeed {
  return { slug, title, type, difficulty, category, order, alsoIn };
}

