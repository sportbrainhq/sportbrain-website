/**
 * Roll of honour for the four Grand Slams, by singles event.
 *
 * The competition pages for the majors rendered almost nothing: Wimbledon
 * carried one derived record and no history, no facts and no winners, which on
 * a tournament first played in 1877 is the most conspicuous gap in the tennis
 * section.
 *
 * ## Five events per tournament
 *
 * Each major carries singles, doubles and mixed doubles: men's singles,
 * women's singles, men's doubles, women's doubles and mixed doubles, as five
 * separate tables. Tennis awards five distinct titles at each Grand Slam and
 * reports them separately, so a page that showed only the singles was showing
 * two fifths of the tournament.
 *
 * A doubles champion is stored as both names in one entry, joined with a
 * slash, because the pair won the title jointly and splitting them into two
 * rows would imply two winners of the same event in the same year. Mixed
 * doubles pairs one man and one woman, which is why it is its own table rather
 * than being filed under either.
 *
 * ## Men's and women's kept apart
 *
 * Two tables per tournament rather than one combined list. Tennis reports its
 * champions this way everywhere, the two events have been contested for
 * different lengths of time (the ladies' singles at Wimbledon began seven years
 * after the gentlemen's), and interleaving them by year would produce a table in
 * which consecutive rows are answers to different questions. `kind` is the
 * conflict target on `entity_ranking`, so the two lists need distinct values or
 * the second would overwrite the first.
 *
 * ## Open Era only
 *
 * Every list starts at 1968. Before then the majors were amateur events that
 * excluded the professionals, so a combined list runs together two eras in which
 * the same trophy meant different things, and tennis itself reports Open Era
 * records separately for exactly that reason. The pre-Open champions are real
 * and are not disowned here; they belong in a second table if anybody wants
 * them, not merged into this one.
 *
 * ## Gaps are real
 *
 * Several years are legitimately absent and are left absent rather than
 * interpolated:
 *
 *   - **Wimbledon 2020**: cancelled, the only year since the Second World War.
 *   - **Australian Open 1986**: not held. The tournament moved from December to
 *     January, so the December 1985 edition was followed by January 1987.
 *   - **Australian Open 1977**: two editions were played, in January and
 *     December, as part of the same move. Only one is recorded here.
 *   - **Australian Open mixed doubles 1970-1986**: the event was not contested
 *     for seventeen years, which is why that table is much shorter than the
 *     other four for the same tournament.
 *   - **US Open mixed doubles 2020**: not held, though the rest of that year's
 *     tournament was played behind closed doors.
 *
 * A missing year in these tables means the tournament was not played or is not
 * recorded, never that the winner was unknown.
 *
 * ## Provenance
 *
 * Extracted from the Wikipedia champion lists at the `asOf` date rather than
 * recalled, and the source URL is stored per table and rendered as the
 * provenance note. Champion names are stored as written; the seeder resolves
 * them against the person table, and an unmatched name renders as plain text
 * rather than a wrong link.
 */
